const fs = require("fs");
const path = "client/src/pages/WorkflowPrototypeLive.tsx";
const source = fs.readFileSync(path, "utf8");
const startMarker = '          <Panel title="Examination" icon={ClipboardList}>';
const endMarker = '          </Panel>\n        </div>\n      ),\n      diagnosis:';
const start = source.indexOf(startMarker);
const end = source.indexOf(endMarker, start);
if (start < 0 || end < 0) throw new Error("Examination panel boundaries not found");
const replacement = [
  '          <Panel title="Examination" icon={ClipboardList}>',
  '            <div className="grid grid-cols-1 gap-2 sm:grid-cols-3" dir="ltr">',
  '              <label className="flex items-center gap-2 rounded-lg border p-2 text-xs">',
  '                <Checkbox',
  '                  checked={data.specialist.externalAppearance.ptosis}',
  '                  onCheckedChange={(checked) =>',
  '                    update("specialist", {',
  '                      ...data.specialist,',
  '                      externalAppearance: { ...data.specialist.externalAppearance, ptosis: checked === true },',
  '                    })',
  '                  }',
  '                />',
  '                Ptosis',
  '              </label>',
  '              <label className="flex items-center gap-2 rounded-lg border p-2 text-xs">',
  '                <Checkbox',
  '                  checked={data.specialist.externalAppearance.squint}',
  '                  onCheckedChange={(checked) =>',
  '                    update("specialist", {',
  '                      ...data.specialist,',
  '                      externalAppearance: { ...data.specialist.externalAppearance, squint: checked === true },',
  '                    })',
  '                  }',
  '                />',
  '                Squint',
  '              </label>',
  '              <Field',
  '                label="Others"',
  '                value={data.specialist.externalAppearance.others}',
  '                onChange={(value) => update("specialist", { ...data.specialist, externalAppearance: { ...data.specialist.externalAppearance, others: value } })}',
  '                dir="ltr"',
  '              />',
  '              <SelectBox',
  '                label="Muscle Action"',
  '                value={data.specialist.muscleAction}',
  '                options={["Normal", "Abnormal"]}',
  '                onChange={(value) => update("specialist", { ...data.specialist, muscleAction: value as "Normal" | "Abnormal" })}',
  '                ariaLabel="Muscle Action"',
  '              />',
  '              <Field',
  '                label="Other Abnormalities"',
  '                value={data.specialist.otherAbnormalities}',
  '                onChange={(value) => update("specialist", { ...data.specialist, otherAbnormalities: value })}',
  '                dir="ltr"',
  '              />',
  '              <SelectBox',
  '                label="Fundus"',
  '                value={data.specialist.fundus}',
  '                options={["Normal", "Abnormal"]}',
  '                onChange={(value) => update("specialist", { ...data.specialist, fundus: value as "Normal" | "Abnormal" })}',
  '                ariaLabel="Fundus"',
  '              />',
  '            </div>',
  '          </Panel>',
  '        </div>',
  '      ),',
  '      diagnosis:',
].join("\n");
fs.writeFileSync(path, source.slice(0, start) + replacement + source.slice(end + endMarker.length), "utf8");
console.log("Examination rebuilt as a three-column LTR grid");
